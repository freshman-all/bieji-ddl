-- 别急 DDL production schema
-- Run this file in Supabase SQL Editor or via Supabase CLI.

create extension if not exists pgcrypto;

create table if not exists public.profiles (
  id uuid primary key references auth.users(id) on delete cascade,
  display_name text,
  mode text not null default 'detail',
  pet_data jsonb not null default '{}'::jsonb,
  keyword_rules jsonb not null default '[]'::jsonb,
  ai_settings jsonb not null default '{}'::jsonb,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.themes (
  user_id uuid not null references auth.users(id) on delete cascade,
  id text not null,
  name text not null,
  icon text not null default '✦',
  color text not null default 'green',
  description text not null default '',
  background_image text not null default '',
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  primary key (user_id, id)
);

create table if not exists public.tasks (
  user_id uuid not null references auth.users(id) on delete cascade,
  id text not null,
  theme_id text not null,
  title text not null,
  category text not null default '作业',
  source text not null default '',
  due_time timestamptz,
  location text not null default '',
  next_action text not null default '',
  requirements text not null default '',
  urgency text not null default 'auto',
  status text not null default 'todo',
  reminder15 boolean not null default false,
  deleted boolean not null default false,
  raw_text_hash text not null default '',
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  primary key (user_id, id)
);

create table if not exists public.ai_usage_logs (
  id bigint generated by default as identity primary key,
  user_id uuid not null references auth.users(id) on delete cascade,
  model text not null default '',
  input_tokens integer not null default 0,
  output_tokens integer not null default 0,
  status text not null default 'ok',
  error_message text,
  created_at timestamptz not null default now()
);

create index if not exists tasks_user_updated_idx on public.tasks(user_id, updated_at desc);
create index if not exists themes_user_updated_idx on public.themes(user_id, updated_at desc);
create index if not exists ai_usage_user_created_idx on public.ai_usage_logs(user_id, created_at desc);

alter table public.profiles enable row level security;
alter table public.themes enable row level security;
alter table public.tasks enable row level security;
alter table public.ai_usage_logs enable row level security;

drop policy if exists "profiles own rows" on public.profiles;
create policy "profiles own rows" on public.profiles for all
using (auth.uid() = id) with check (auth.uid() = id);

drop policy if exists "themes own rows" on public.themes;
create policy "themes own rows" on public.themes for all
using (auth.uid() = user_id) with check (auth.uid() = user_id);

drop policy if exists "tasks own rows" on public.tasks;
create policy "tasks own rows" on public.tasks for all
using (auth.uid() = user_id) with check (auth.uid() = user_id);

drop policy if exists "usage own reads" on public.ai_usage_logs;
create policy "usage own reads" on public.ai_usage_logs for select
using (auth.uid() = user_id);

create or replace function public.handle_new_user()
returns trigger
language plpgsql
security definer set search_path = public
as $$
begin
  insert into public.profiles (id) values (new.id)
  on conflict (id) do nothing;
  return new;
end;
$$;

drop trigger if exists on_auth_user_created on auth.users;
create trigger on_auth_user_created
after insert on auth.users
for each row execute procedure public.handle_new_user();

create or replace function public.load_user_snapshot()
returns jsonb
language sql
security invoker
stable
set search_path = public
as $$
  select jsonb_build_object(
    'profile', coalesce((
      select jsonb_build_object(
        'mode', p.mode,
        'pet', p.pet_data,
        'keywordRules', p.keyword_rules,
        'aiSettings', p.ai_settings
      ) from public.profiles p where p.id = auth.uid()
    ), '{}'::jsonb),
    'themes', coalesce((
      select jsonb_agg(jsonb_build_object(
        'id', t.id,
        'name', t.name,
        'icon', t.icon,
        'color', t.color,
        'description', t.description,
        'backgroundImage', t.background_image
      ) order by t.created_at)
      from public.themes t where t.user_id = auth.uid()
    ), '[]'::jsonb),
    'tasks', coalesce((
      select jsonb_agg(jsonb_build_object(
        'id', t.id,
        'themeId', t.theme_id,
        'title', t.title,
        'category', t.category,
        'source', t.source,
        'dueTime', t.due_time,
        'location', t.location,
        'nextAction', t.next_action,
        'requirements', t.requirements,
        'urgency', t.urgency,
        'status', t.status,
        'reminder15', t.reminder15,
        'deleted', t.deleted,
        'rawTextHash', t.raw_text_hash
      ) order by t.created_at)
      from public.tasks t where t.user_id = auth.uid()
    ), '[]'::jsonb)
  );
$$;

create or replace function public.save_user_snapshot(payload jsonb)
returns void
language plpgsql
security invoker
set search_path = public
as $$
declare
  uid uuid := auth.uid();
  item jsonb;
  keep_theme_ids text[];
  keep_task_ids text[];
begin
  if uid is null then
    raise exception 'Authentication required';
  end if;

  insert into public.profiles (id) values (uid)
  on conflict (id) do nothing;

  update public.profiles
  set mode = coalesce(payload->'profile'->>'mode', mode),
      pet_data = coalesce(payload->'profile'->'pet', pet_data),
      keyword_rules = coalesce(payload->'profile'->'keywordRules', keyword_rules),
      ai_settings = coalesce(payload->'profile'->'aiSettings', ai_settings),
      updated_at = now()
  where id = uid;

  select coalesce(array_agg(value->>'id'), '{}'::text[])
  into keep_theme_ids
  from jsonb_array_elements(coalesce(payload->'themes', '[]'::jsonb));

  select coalesce(array_agg(value->>'id'), '{}'::text[])
  into keep_task_ids
  from jsonb_array_elements(coalesce(payload->'tasks', '[]'::jsonb));

  delete from public.tasks
  where user_id = uid and not (id = any(keep_task_ids));

  delete from public.themes
  where user_id = uid and not (id = any(keep_theme_ids));

  for item in select value from jsonb_array_elements(coalesce(payload->'themes', '[]'::jsonb))
  loop
    insert into public.themes
      (user_id, id, name, icon, color, description, background_image, updated_at)
    values
      (uid, item->>'id', coalesce(item->>'name', '未命名主题'), coalesce(item->>'icon', '✦'),
       coalesce(item->>'color', 'green'), coalesce(item->>'description', ''),
       coalesce(item->>'backgroundImage', ''), now())
    on conflict (user_id, id) do update set
      name = excluded.name,
      icon = excluded.icon,
      color = excluded.color,
      description = excluded.description,
      background_image = excluded.background_image,
      updated_at = now();
  end loop;

  for item in select value from jsonb_array_elements(coalesce(payload->'tasks', '[]'::jsonb))
  loop
    insert into public.tasks
      (user_id, id, theme_id, title, category, source, due_time, location, next_action,
       requirements, urgency, status, reminder15, deleted, raw_text_hash, updated_at)
    values
      (uid, item->>'id', coalesce(item->>'themeId', 'study'), coalesce(item->>'title', '未命名任务'),
       coalesce(item->>'category', '作业'), coalesce(item->>'source', ''),
       nullif(item->>'dueTime', '')::timestamptz, coalesce(item->>'location', ''),
       coalesce(item->>'nextAction', ''), coalesce(item->>'requirements', ''),
       coalesce(item->>'urgency', 'auto'), coalesce(item->>'status', 'todo'),
       coalesce((item->>'reminder15')::boolean, false),
       coalesce((item->>'deleted')::boolean, false), coalesce(item->>'rawTextHash', ''), now())
    on conflict (user_id, id) do update set
      theme_id = excluded.theme_id,
      title = excluded.title,
      category = excluded.category,
      source = excluded.source,
      due_time = excluded.due_time,
      location = excluded.location,
      next_action = excluded.next_action,
      requirements = excluded.requirements,
      urgency = excluded.urgency,
      status = excluded.status,
      reminder15 = excluded.reminder15,
      deleted = excluded.deleted,
      raw_text_hash = excluded.raw_text_hash,
      updated_at = now();
  end loop;
end;
$$;

-- Enable Realtime if desired. Polling also works without it.
do $$
begin
  if not exists (
    select 1 from pg_publication_tables
    where pubname = 'supabase_realtime' and schemaname = 'public' and tablename = 'tasks'
  ) then
    alter publication supabase_realtime add table public.tasks;
  end if;
  if not exists (
    select 1 from pg_publication_tables
    where pubname = 'supabase_realtime' and schemaname = 'public' and tablename = 'themes'
  ) then
    alter publication supabase_realtime add table public.themes;
  end if;
end;
$$;
